"""Benchmark toolism on every snapshot in bench/snapshots/ and write RESULTS.md + results.json.

    uv run python bench/run.py

Tokenizers: heuristic always; tiktoken o200k_base / cl100k_base when their vocabularies load;
anthropic:<model> when ANTHROPIC_API_KEY is set (model from TOOLISM_BENCH_ANTHROPIC_MODEL).
Use --offline to exclude remote tokenizers; --check compares the committed baseline without writing.
"""

from __future__ import annotations

import argparse
import datetime as dt
import importlib.metadata
import json
import os
import statistics
import sys
from fractions import Fraction
from pathlib import Path
from typing import Any

from toolism.__about__ import __version__
from toolism.errors import ToolismError
from toolism.formats import parse
from toolism.measurement import measure
from toolism.pipeline import slim
from toolism.rules import all_rules
from toolism.tokenizers import Tokenizer, get_tokenizer

BENCH = Path(__file__).resolve().parent
LEVELS = ("safe", "annotations")
COMMAND = "uv run python bench/run.py"
OFFLINE_TOKENIZERS = ("tiktoken:o200k_base", "tiktoken:cl100k_base", "heuristic")


def available_tokenizers(*, offline: bool = False) -> list[Tokenizer]:
    specs = list(OFFLINE_TOKENIZERS)
    if not offline and os.environ.get("ANTHROPIC_API_KEY"):
        model = os.environ.get("TOOLISM_BENCH_ANTHROPIC_MODEL", "claude-sonnet-5-5")
        specs.insert(0, f"anthropic:{model}")
    found = []
    for spec in specs:
        tokenizer = get_tokenizer(spec)
        try:
            tokenizer.count_tools(())
            tokenizer.count_tools(parse([{"name": "probe", "input_schema": {}}]).tools)
        except ToolismError as exc:
            if offline:
                raise
            print(f"skipping {spec}: {exc.message}", file=sys.stderr)
            continue
        found.append(tokenizer)
    return found


def sources() -> dict[str, dict[str, str]]:
    import tomllib

    with (BENCH / "servers.toml").open("rb") as handle:
        known = {s["name"]: s for s in tomllib.load(handle)["server"]}
    sdk = importlib.metadata.version("mcp")
    known["fastmcp-pydantic"] = {
        "package": f"generated by bench/make_pydantic.py (mcp {sdk})",
        "version": "",
        "notes": "Typical Python server: Pydantic models and docstrings.",
    }
    return known


def bench_snapshot(path: Path, tokenizers: list[Tokenizer]) -> dict[str, Any]:
    toolset = parse(json.loads(path.read_text(encoding="utf-8")))
    entry: dict[str, Any] = {"name": path.stem, "tools": len(toolset.function_tools())}
    entry["levels"] = {}
    for level in LEVELS:
        per_tokenizer: dict[str, Any] = {}
        for tokenizer in tokenizers:
            result = slim(toolset, level=level, tokenizer=tokenizer)
            report = result.report
            per_tokenizer[tokenizer.name] = {
                "before": report.before,
                "after": report.after,
                "saved": report.saved,
                "saved_pct": round(report.saved_pct, 2),
            }
            if tokenizer is tokenizers[0]:
                per_tokenizer["rules"] = {
                    r.rule_id: r.tokens_saved for r in report.rules if r.tokens_saved
                }
                per_tokenizer["attribution_tokenizer"] = report.attribution_tokenizer
        entry["levels"][level] = per_tokenizer
    entry["unslimmed"] = {t.name: measure(toolset, t).total for t in tokenizers}
    return entry


def _pct(value: float) -> str:
    return f"{value:.1f}%"


def _n(value: int) -> str:
    return f"{value:,}"


def render(results: dict[str, Any]) -> str:
    primary = results["primary_tokenizer"]
    rows = results["snapshots"]
    names = {r.id: r.name for r in all_rules()}
    lines = [
        "# Benchmark",
        "",
        "<!-- Generated by `uv run python bench/run.py`. Do not edit by hand. -->",
        "",
        f"toolism {results['toolism_version']} on {len(rows)} tool sets "
        f"({results['total_tools']} tools), {results['date']}. Token counts use "
        f"`{primary}` on toolism's provider-neutral rendering of each tool "
        "(see [Methodology](#methodology)).",
        "",
        "## Default rules (`--level safe`, validation-equivalent)",
        "",
        "| Tool set | Tools | Before | After | Saved | Biggest rule |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in rows:
        safe = row["levels"]["safe"]
        stats = safe[primary]
        rules = sorted(safe["rules"].items(), key=lambda kv: -kv[1])
        top = f"{rules[0][0]} {names.get(rules[0][0], '')}" if rules else "—"
        lines.append(
            f"| [{row['name']}](snapshots/{row['name']}.json) | {row['tools']} | "
            f"{_n(stats['before'])} | {_n(stats['after'])} | "
            f"{_n(stats['saved'])} ({_pct(stats['saved_pct'])}) | {top} |"
        )
    totals = results["totals"]["safe"]
    lines += [
        f"| **All** | **{results['total_tools']}** | **{_n(totals['before'])}** | "
        f"**{_n(totals['after'])}** | **{_n(totals['saved'])} ({_pct(totals['saved_pct'])})** | |",
        "",
        f"Median saving per tool set: **{_pct(results['median_saved_pct']['safe'])}**. "
        "The total is dominated by the largest tool sets; the median is the typical case.",
        "",
        "## With lossy annotation rules (`--level annotations`)",
        "",
        "| Tool set | Safe | Annotations |",
        "| --- | ---: | ---: |",
    ]
    for row in rows:
        safe = row["levels"]["safe"][primary]["saved_pct"]
        lossy = row["levels"]["annotations"][primary]["saved_pct"]
        lines.append(f"| {row['name']} | {_pct(safe)} | {_pct(lossy)} |")
    lines += [
        f"| **Median** | **{_pct(results['median_saved_pct']['safe'])}** | "
        f"**{_pct(results['median_saved_pct']['annotations'])}** |",
        "",
    ]
    names_t = results["tokenizers"]
    if len(names_t) > 1:
        lines += [
            "## Across tokenizers (`--level safe`, % saved)",
            "",
            "| Tool set | " + " | ".join(f"`{t}`" for t in names_t) + " |",
            "| --- | " + " | ".join("---:" for _ in names_t) + " |",
        ]
        for row in rows:
            cells = [_pct(row["levels"]["safe"][t]["saved_pct"]) for t in names_t]
            lines.append(f"| {row['name']} | " + " | ".join(cells) + " |")
        lines.append("")
    calibration = results.get("heuristic_calibration")
    if calibration:
        lines += [
            "## Heuristic tokenizer accuracy",
            "",
            f"The offline `heuristic` tokenizer against `{calibration['reference']}` on the "
            f"unslimmed tool sets: mean absolute error **{_pct(calibration['mean_abs_pct'])}**, "
            f"mean signed error {calibration['mean_signed_pct']:+.1f}% "
            f"(worst {calibration['worst']['name']}: "
            f"{calibration['worst']['error_pct']:+.1f}%).",
            "",
        ]
    lines += [
        "## Sources",
        "",
        "| Tool set | Package | Version | Notes |",
        "| --- | --- | --- | --- |",
    ]
    for row in rows:
        src = row["source"]
        lines.append(f"| {row['name']} | {src['package']} | {src['version']} | {src['notes']} |")
    lines += [
        "",
        "## Methodology",
        "",
        "- Snapshots are the exact `tools/list` results, collected with "
        "`uv run python bench/collect.py` (pinned versions in `servers.toml`) and committed, "
        "so every number here is reproducible offline.",
        "- Each tool is counted as compact JSON of `{name, description, parameters}`. This is "
        "an approximation of what a provider feeds the model: providers wrap tools in their "
        "own prompt format, which adds a roughly constant overhead per tool that toolism "
        "cannot remove. `anthropic:<model>` uses Anthropic's `count_tokens` API, which is "
        "exact for Claude.",
        '- "Biggest rule" attributes savings to rules with the '
        f"`{rows[0]['levels']['safe']['attribution_tokenizer'] if rows else primary}` tokenizer.",
        "- Every changed schema in every snapshot is checked for validation equivalence, both "
        "ways, by `tests/test_bench.py` in CI; the run is also checked to be idempotent.",
        f"- Reproduce with `{COMMAND}`.",
        "",
    ]
    return "\n".join(lines)


def collect_results(tokenizers: list[Tokenizer]) -> dict[str, Any]:
    known = sources()
    snapshots = sorted((BENCH / "snapshots").glob("*.json"))
    rows = []
    for path in snapshots:
        row = bench_snapshot(path, tokenizers)
        info = known.get(path.stem, {"package": "?", "version": "?", "notes": ""})
        row["source"] = {k: info.get(k, "") for k in ("package", "version", "notes")}
        rows.append(row)
        print(f"{path.stem}: done", file=sys.stderr)
    primary = tokenizers[0].name
    results: dict[str, Any] = {
        "toolism_report": 1,
        "kind": "benchmark",
        "toolism_version": __version__,
        "date": dt.date.today().isoformat(),
        "command": COMMAND,
        "tokenizers": [t.name for t in tokenizers],
        "primary_tokenizer": primary,
        "total_tools": sum(r["tools"] for r in rows),
        "snapshots": rows,
        "totals": {},
        "median_saved_pct": {},
    }
    for level in LEVELS:
        before = sum(r["levels"][level][primary]["before"] for r in rows)
        after = sum(r["levels"][level][primary]["after"] for r in rows)
        results["totals"][level] = {
            "before": before,
            "after": after,
            "saved": before - after,
            "saved_pct": round(100.0 * (before - after) / before, 2) if before else 0.0,
        }
        results["median_saved_pct"][level] = round(
            statistics.median(r["levels"][level][primary]["saved_pct"] for r in rows), 2
        )
    reference = next((t.name for t in tokenizers if t.name.startswith("tiktoken:o200k")), None)
    if reference and "heuristic" in results["tokenizers"]:
        errors = [
            {
                "name": r["name"],
                "error_pct": round(
                    100.0
                    * (r["unslimmed"]["heuristic"] - r["unslimmed"][reference])
                    / r["unslimmed"][reference],
                    2,
                ),
            }
            for r in rows
            if r["unslimmed"][reference]
        ]
        results["heuristic_calibration"] = {
            "reference": reference,
            "mean_abs_pct": round(statistics.mean(abs(e["error_pct"]) for e in errors), 2),
            "mean_signed_pct": round(statistics.mean(e["error_pct"] for e in errors), 2),
            "worst": max(errors, key=lambda e: abs(e["error_pct"])),
            "per_snapshot": errors,
        }
    return results


def offline_rows(report: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Validate the report dimensions needed by the savings gate."""
    if report["toolism_report"] != 1 or report["kind"] != "benchmark":
        raise ValueError("expected a version 1 benchmark report")
    if not set(OFFLINE_TOKENIZERS).issubset(report["tokenizers"]):
        raise ValueError("benchmark report is missing required offline tokenizers")
    rows = {}
    for row in report["snapshots"]:
        name = row["name"]
        if not isinstance(name, str) or not name or name in rows:
            raise ValueError(f"invalid or duplicate tool set: {name!r}")
        if type(row["tools"]) is not int or row["tools"] < 0:
            raise ValueError(f"{name}: invalid tool count")
        rows[name] = row
    if not rows:
        raise ValueError("benchmark report has no tool sets")
    return rows


def savings(row: dict[str, Any], level: str, tokenizer: str) -> tuple[int, int, Fraction]:
    stats = row["levels"][level][tokenizer]
    before, after, saved = (stats[key] for key in ("before", "after", "saved"))
    if (
        any(type(value) is not int for value in (before, after, saved))
        or before < 0
        or after < 0
        or saved != before - after
        or (before == 0 and after != 0)
    ):
        raise ValueError(f"{row['name']} / {level} / {tokenizer}: invalid token counts")
    return before, saved, Fraction(100 * saved, before) if before else Fraction(0)


def compare_results(
    baseline: dict[str, Any], current: dict[str, Any], margin_pp: Fraction
) -> list[str]:
    """Compare exact savings rates, not rounded percentages or aggregate totals."""
    old, new = offline_rows(baseline), offline_rows(current)
    if old.keys() != new.keys():
        raise ValueError(
            f"tool sets changed; missing={sorted(old.keys() - new.keys())}, "
            f"new={sorted(new.keys() - old.keys())}; regenerate the baseline deliberately"
        )
    failures = []
    for name in sorted(old):
        if old[name]["tools"] != new[name]["tools"]:
            raise ValueError(f"{name}: tool count changed; regenerate the baseline deliberately")
        for level in LEVELS:
            for tokenizer in OFFLINE_TOKENIZERS:
                before, saved, rate = savings(old[name], level, tokenizer)
                new_before, new_saved, new_rate = savings(new[name], level, tokenizer)
                if before != new_before:
                    raise ValueError(
                        f"{name} / {level} / {tokenizer}: unslimmed count changed "
                        f"({before} -> {new_before}); regenerate the baseline deliberately"
                    )
                loss = rate - new_rate
                if loss > margin_pp:
                    failures.append(
                        f"{name} / {level} / {tokenizer}: savings {saved} -> {new_saved} tokens; "
                        f"lost {float(loss):.6f} percentage points "
                        f"(allowed {float(margin_pp):.6f})"
                    )
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="use only local tokenizers")
    parser.add_argument("--check", action="store_true", help="compare without rewriting results")
    parser.add_argument(
        "--max-loss-pp",
        type=Fraction,
        default=None,
        help="explicit allowed loss in percentage points (default: no loss)",
    )
    args = parser.parse_args(argv)
    if args.max_loss_pp is not None and (not args.check or args.max_loss_pp < 0):
        parser.error("--max-loss-pp requires --check and a non-negative value")
    try:
        baseline = (
            json.loads((BENCH / "results.json").read_text(encoding="utf-8")) if args.check else None
        )
        results = collect_results(available_tokenizers(offline=args.check or args.offline))
        if args.check:
            failures = compare_results(baseline, results, args.max_loss_pp or Fraction(0))
            for failure in failures:
                print(failure, file=sys.stderr)
            if not failures:
                print("Benchmark savings check passed")
            return int(bool(failures))
    except (OSError, ValueError, KeyError, TypeError, ToolismError) as exc:
        print(f"Benchmark failed: {exc}", file=sys.stderr)
        return 1
    (BENCH / "results.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (BENCH / "RESULTS.md").write_text(render(results), encoding="utf-8")
    print(f"wrote {BENCH / 'RESULTS.md'}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
